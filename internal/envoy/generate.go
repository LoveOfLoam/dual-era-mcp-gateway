// Package envoy generates a draft Envoy bootstrap for the B1 topology.
// The generated config is intentionally a starting point: production should add
// TLS, ext_authz, rate limit, tracing, and Envoy version-specific tuning.
package envoy

import (
	"fmt"
	"net/url"
	"strconv"
	"strings"

	"dual-era-mcp-gateway/internal/source"
)

// Config controls the generated topology.
type Config struct {
	PublicPort   int
	InternalPort int
	ModernHost   string
	ModernPort   int
	Sources      []source.SourceSpec
}

// Generate returns a YAML string with the public and internal listeners plus
// one cluster per source.
func Generate(cfg Config) (string, error) {
	if cfg.PublicPort == 0 {
		cfg.PublicPort = 8443
	}
	if cfg.InternalPort == 0 {
		cfg.InternalPort = 10001
	}
	if cfg.ModernHost == "" {
		cfg.ModernHost = "modern-facade"
	}
	if cfg.ModernPort == 0 {
		cfg.ModernPort = 8080
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by dual-era-mcp-gateway. Draft only.
static_resources:
  listeners:
    - name: public
      address:
        socket_address: {address: 0.0.0.0, port_value: %d}
      filter_chains:
        - filters:
            - name: envoy.filters.network.http_connection_manager
              typed_config:
                "@type": type.googleapis.com/envoy.extensions.filters.network.http_connection_manager.v3.HttpConnectionManager
                stat_prefix: public
                route_config:
                  name: public
                  virtual_hosts:
                    - name: public
                      domains: ["*"]
                      routes:
                        - match: {prefix: "/modern/mcp"}
                          route: {cluster: modern_facade}
                        - match: {prefix: "/mcp"}
                          route: {cluster: legacy_internal}
                        - match: {prefix: "/healthz"}
                          direct_response: {status: 200, body: {inline_string: "ok"}}
                http_filters:
                  - name: envoy.filters.http.mcp
                    typed_config:
                      "@type": type.googleapis.com/envoy.extensions.filters.http.mcp.v3.Mcp
                      traffic_mode: PASS_THROUGH
                  - name: envoy.filters.http.router
                    typed_config:
                      "@type": type.googleapis.com/envoy.extensions.filters.http.router.v3.Router
    - name: legacy_internal
      address:
        socket_address: {address: 0.0.0.0, port_value: %d}
      filter_chains:
        - filters:
            - name: envoy.filters.network.http_connection_manager
              typed_config:
                "@type": type.googleapis.com/envoy.extensions.filters.network.http_connection_manager.v3.HttpConnectionManager
                stat_prefix: legacy_internal
                route_config:
                  name: legacy_internal
                  virtual_hosts:
                    - name: legacy
                      domains: ["*"]
                      routes:
                        - match: {prefix: "/"}
                          route: {cluster: mcp_multicluster}
                http_filters:
                  - name: envoy.filters.http.mcp
                    typed_config:
                      "@type": type.googleapis.com/envoy.extensions.filters.http.mcp.v3.Mcp
                      traffic_mode: PASS_THROUGH
                  - name: envoy.filters.http.mcp_router
                    typed_config:
                      "@type": type.googleapis.com/envoy.extensions.filters.http.mcp_router.v3.McpRouter
                      servers: []
  clusters:
    - name: modern_facade
      type: STRICT_DNS
      connect_timeout: 1s
      load_assignment:
        cluster_name: modern_facade
        endpoints:
          - lb_endpoints:
              - endpoint:
                  address:
                    socket_address: {address: %s, port_value: %d}
    - name: legacy_internal
      type: STRICT_DNS
      connect_timeout: 1s
      load_assignment:
        cluster_name: legacy_internal
        endpoints:
          - lb_endpoints:
              - endpoint:
                  address:
                    socket_address: {address: 127.0.0.1, port_value: %d}
    - name: mcp_multicluster
      connect_timeout: 0.25s
      lb_policy: CLUSTER_PROVIDED
      cluster_type:
        name: envoy.clusters.mcp_multicluster
        typed_config:
          "@type": type.googleapis.com/envoy.extensions.clusters.mcp_multicluster.v3.ClusterConfig
          servers:
`, cfg.PublicPort, cfg.InternalPort, cfg.ModernHost, cfg.ModernPort, cfg.InternalPort)

	for _, s := range cfg.Sources {
		cluster, host, port, err := clusterFor(s)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, `            - name: %s
              mcp_cluster: {cluster: %s, path: /mcp}
`, s.Name, cluster)
		fmt.Fprintf(&b, `    - name: %s
      type: STRICT_DNS
      connect_timeout: 1s
      load_assignment:
        cluster_name: %s
        endpoints:
          - lb_endpoints:
              - endpoint:
                  address:
                    socket_address: {address: %s, port_value: %d}
`, cluster, cluster, host, port)
	}
	return b.String(), nil
}

func clusterFor(s source.SourceSpec) (cluster, host string, port int, err error) {
	raw := s.Endpoint
	if s.Type == source.TypeREST {
		raw = s.BaseURL
	}
	u, err := url.Parse(raw)
	if err != nil || u.Hostname() == "" {
		return "", "", 0, fmt.Errorf("source %q: invalid endpoint %q", s.Name, raw)
	}
	host = u.Hostname()
	port = 443
	if u.Port() != "" {
		p, convErr := strconv.Atoi(u.Port())
		if convErr != nil {
			return "", "", 0, fmt.Errorf("source %q: invalid port", s.Name)
		}
		port = p
	} else if u.Scheme == "http" {
		port = 80
	}
	cluster = s.Name
	if s.Type == source.TypeREST {
		cluster = s.Name + "_rest"
	}
	return cluster, host, port, nil
}
